def split_translation(text):
    """Keep each numbered phrase paired with its own constraints."""
    if not text:
        return text, []
    lines, notes = [], []
    for line in text.splitlines():
        number = re.match(r'^[①②]\s*', line)
        prefix = number.group(0) if number else ''
        body = line[len(prefix):]
        kept = []
        for sentence in re.split(r'(?<=[.!?])\s+', body):
            if sentence in CONDITIONS:
                notes.append(prefix + CONDITIONS[sentence])
            elif re.match(r'^(Выбери|Вставь|Используй|Образуй|Заверши)\b', sentence):
                note = re.sub(r'^(Выбери|Вставь|Используй|Образуй|Заверши)\s+', '', sentence).rstrip('.')
                notes.append(prefix + note[0].upper() + note[1:])
            else:
                kept.append(sentence)
        if kept:
            lines.append(prefix + ' '.join(kept))
    return '\n'.join(lines), list(dict.fromkeys(notes))


def edit_bank(bank):
    metadata = {}
    for row in RULES.strip().splitlines():
        ref, title, form, meaning, nuance = row.split('|')
        lesson, rule = map(int, ref.split('.'))
        metadata[f'umi-l{lesson:02}.g{rule:02}'] = (title, form, meaning, nuance)
    rules = {r['id']: r for l in bank['lessons'] for r in l['rules']}
    assert set(rules) == set(metadata), 'Each rule needs authored metadata'
    for rid, r in rules.items():
        r['titleRu'], r['form'], r['meaningRu'], r['nuanceRu'] = metadata[rid]
        r['applicationRu'] = r['formationRu']
        r['translationRu'], r['conditionsRu'] = split_translation(r['translationRu'])
    # Complete the conjugation recipes shown under "Как построить".
    rules['umi-l03.g01']['applicationRu'] = 'る-глагол: убери る и добавь ます — たべる → たべます.\nう-глагол: замени конечную у-гласную на и и добавь ます — よむ → よみます.\nИсключения: する → します; くる → きます.'
    rules['umi-l06.g01']['applicationRu'] = 'る-глагол: る → て.\nう・つ・る → って; む・ぶ・ぬ → んで; く → いて; ぐ → いで; す → して.\nИсключения: いく → いって; する → して; くる → きて.'
    rules['umi-l13.g01']['applicationRu'] = 'る-глагол: る → られる — たべる → たべられる.\nう-глагол: конечная у-гласная → э + る — よむ → よめる; およぐ → およげる.\nИсключения: する → できる; くる → こられる.\nВежливая форма: убери конечное る и добавь ます — およげる → およげます.'
    for e in bank['exercises']:
        if e['id'] == 'umi-l13.g01.variant.order':
            e['version'] = 2
            e['previousOrder'] = {'ids': ['b0', 'b1', 'b2', 'b3', 'b4', 'b5', 'extra'], 'removed': ['b2', 'b3', 'b4'], 'aliases': {'b5': 'b2'}}
        e['translationRu'], e['conditionsRu'] = split_translation(e.get('translationRu'))
        if e['type'] == 'order':
            first = next(o['text'] for o in e['options'] if o['id'] == e['acceptedSequences'][0][0])
            extra = len(e['options']) - e['requiredCount']
            e['labelRu'] = 'Перевод из блоков'
